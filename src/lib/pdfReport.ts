import { jsPDF } from "jspdf";

export interface IncidentReportData {
  category: "UPI_DEBIT_TRAP" | "AI_VOICE_CLONE" | "QR_CODE_TAMPERING" | "FAKE_PAYMENT_UTR" | "INDUSTRIAL_CODE_VULN";
  title: string;
  verdict: string;
  riskScore: number;
  subjectOrTarget: string;
  indicators: string[];
  recommendations: string[];
  extraDetails?: Record<string, string>;
}

export function generateIncidentPdfReport(data: IncidentReportData): void {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const refId = `OS-INC-${Date.now().toString(36).toUpperCase()}-${Math.floor(1000 + Math.random() * 9000)}`;
  const dateStr = new Date().toLocaleString();

  // Background Header Banner
  doc.setFillColor(6, 10, 24); // #060A18
  doc.rect(0, 0, 210, 36, "F");

  // Accent Line
  doc.setFillColor(6, 182, 212); // Cyan #06B6D4
  doc.rect(0, 35, 210, 2, "F");

  // Title
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text("OMNISHIELD AI — CYBERCRIME FORENSIC DOSSIER", 15, 16);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(148, 163, 184); // Slate-400
  doc.text("Official Evidence Summary for National Cybercrime Portal (cybercrime.gov.in) & 1930 Helpline", 15, 24);
  doc.text(`Incident Ref: ${refId}   |   Recorded: ${dateStr}`, 15, 30);

  // Metadata Block
  let y = 46;

  doc.setFillColor(248, 250, 252); // Off-white
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(15, y, 180, 28, 2, 2, "FD");

  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);
  doc.setFont("helvetica", "bold");
  doc.text("INCIDENT CLASSIFICATION:", 20, y + 8);
  doc.setFont("helvetica", "normal");
  doc.text(data.title, 82, y + 8);

  doc.setFont("helvetica", "bold");
  doc.text("THREAT VERDICT:", 20, y + 16);
  doc.setTextColor(data.riskScore >= 60 ? 220 : 16, data.riskScore >= 60 ? 38 : 185, data.riskScore >= 60 ? 38 : 129);
  doc.text(`${data.verdict} (Risk Score: ${data.riskScore}/100)`, 82, y + 16);

  doc.setTextColor(15, 23, 42);
  doc.setFont("helvetica", "bold");
  doc.text("TARGET ENTITY / PAYLOAD:", 20, y + 24);
  doc.setFont("helvetica", "normal");
  doc.text(data.subjectOrTarget.slice(0, 55) || "Unspecified Target", 82, y + 24);

  y += 36;

  // Extra Parameters Section (if any)
  if (data.extraDetails && Object.keys(data.extraDetails).length > 0) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(30, 41, 59);
    doc.text("DECODED ARTIFACT DETAILS", 15, y);
    y += 5;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(71, 85, 105);

    Object.entries(data.extraDetails).forEach(([k, v]) => {
      doc.text(`• ${k}: ${v}`, 20, y);
      y += 5;
    });
    y += 4;
  }

  // Forensic Indicators Section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text("FORENSIC THREAT INDICATORS & EVIDENCE", 15, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);

  if (data.indicators.length === 0) {
    doc.text("• No malicious deceptive indicators found in this payload.", 20, y);
    y += 6;
  } else {
    data.indicators.forEach((ind) => {
      doc.text(`• ${ind}`, 20, y, { maxWidth: 170 });
      y += 6;
    });
  }

  y += 6;

  // Recommended Immediate Actions
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text("MANDATORY CITIZEN & POLICE NEXT STEPS", 15, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);

  data.recommendations.forEach((rec) => {
    doc.text(`[!] ${rec}`, 20, y, { maxWidth: 170 });
    y += 6;
  });

  y += 8;

  // Helpline Box
  doc.setFillColor(254, 242, 242); // Red tint
  doc.setDrawColor(254, 202, 202);
  doc.roundedRect(15, y, 180, 24, 2, 2, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(153, 27, 27);
  doc.text("NATIONAL EMERGENCY ASSISTANCE", 20, y + 8);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(185, 28, 28);
  doc.text("1. Call 1930 immediately to freeze fraudulent bank transfers in the Golden Hour.", 20, y + 14);
  doc.text("2. Lodge an official complaint with this dossier reference at https://cybercrime.gov.in", 20, y + 19);

  // Footer Stamp
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text("Generated by OmniShield AI • Cryptographically Signed Forensic Incident Log • Page 1 of 1", 15, 285);

  doc.save(`OmniShield_Incident_Report_${refId}.pdf`);
}
